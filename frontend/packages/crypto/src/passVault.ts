import { getCryptoWasm } from './rustWasm'

// Kutup Pass vault secrets (docs/plans/pass.md, "Vault secrets"): what opens
// a vault, sealed under the master key and bound to the vault's file id, in
// Rust (kutup-crypto `pass_vault`). A password the person chose is kept only
// as its SHA-256 (the password's part of KeePass's composite key, which opens
// the vault without telling the password); one Kutup Pass generated is kept as
// it is, so it can be shown for a KeePass app.

/** What is kept for a vault: a password and/or a key file (base64). */
export interface PassVaultSecretInput {
  password: string | null
  keyFile: string | null
  /** The password was generated by Kutup Pass (kept, to be shown). */
  generated: boolean
}

/** What a kept vault key holds (bytes in base64). */
export interface PassVaultSecret {
  /** SHA-256 of the password, whichever way it was kept. */
  passwordHash: string | null
  /** The password, when Kutup Pass generated it. */
  generatedPassword: string | null
  keyFile: string | null
}

export async function sealPassVaultSecret(masterKeyBase64: string, binding: string, fileId: string, secret: PassVaultSecretInput): Promise<string> {
  return (await getCryptoWasm()).sealPassVaultSecret(masterKeyBase64, binding, fileId, secret.password, secret.keyFile, secret.generated)
}

export async function openPassVaultSecret(envelope: string, masterKeyBase64: string, binding: string, fileId: string): Promise<PassVaultSecret> {
  return (await getCryptoWasm()).openPassVaultSecret(envelope, masterKeyBase64, binding, fileId)
}
