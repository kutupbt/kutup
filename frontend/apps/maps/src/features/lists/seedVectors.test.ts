// The seeds a file's first editor makes (deterministicSeed), as exact bytes
// shared with Rust (crates/kutup-collab, on yrs): two implementations of one
// encoding, pinned to one set of vectors (docs/plans/cli-yjs-sync.md). A Yjs
// or yrs version bump must keep this and the Rust test passing.
//
// KUTUP_WRITE_SEED_VECTORS=1 rewrites the file from this implementation.

import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { describe, expect, it } from 'vitest'
import { deterministicSeed } from '@kutup/collab/session'
import { fillDoc, type Place } from '@kutup/map/list'

/** The repository root: the nearest folder up from here holding `crates/kutup-collab`. */
function repoRoot(): string {
  let dir = process.cwd()
  while (!existsSync(join(dir, 'crates', 'kutup-collab'))) {
    const up = dirname(dir)
    if (up === dir) throw new Error('crates/kutup-collab not found above the working directory')
    dir = up
  }
  return dir
}

const FILE = join(repoRoot(), 'crates', 'kutup-collab', 'tests', 'vectors', 'seeds.json')
const FILE_ID = '11111111-1111-4111-8111-111111111111'

const TEXTS: Record<string, string> = {
  empty: '',
  note: '# Plans\n\n- milk\n- bread\n',
  code: 'fn main() {\n    println!("hi");\n}\n',
  // Non-BMP (two UTF-16 units each) and Turkish letters.
  unicode: '😀 İstanbul ılık ŞĞÜÖÇ 🎉\n',
}

const PLACES: Place[] = [
  { id: 'p1', name: 'Galata Kulesi', note: 'sunset', lat: 41.0256, lon: 28.9741, addedBy: 'ali@kutup.dev', addedAt: '2026-01-02T10:00:00.000Z' },
  { id: 'p2', name: 'Kız Kulesi 🗼', note: '', lat: 41.021, lon: 29.0041, addedBy: 'ali@kutup.dev', addedAt: '2026-01-02T11:00:00.000Z' },
  { id: 'p3', name: 'Zero', note: 'integers', lat: 41, lon: 29, addedBy: 'ali@kutup.dev', addedAt: '2026-01-03T00:00:00.000Z' },
]

const hex = (bytes: Uint8Array) => Buffer.from(bytes).toString('hex')

function current() {
  return {
    description:
      'Seeds a file’s first editor makes (deterministicSeed: Yjs client id = FNV-1a of the file id, the content inserted once, a Yjs V1 update). Generated by the web (Yjs, frontend/apps/maps/src/features/lists/seedVectors.test.ts); crates/kutup-collab (yrs) must produce the same bytes. A Yjs or yrs bump must keep both passing.',
    fileId: FILE_ID,
    texts: Object.entries(TEXTS).map(([name, text]) => ({
      name,
      text,
      seed: hex(deterministicSeed(FILE_ID, (doc) => doc.getText('content').insert(0, text))),
    })),
    list: { places: PLACES, seed: hex(deterministicSeed(FILE_ID, (doc) => fillDoc(doc, PLACES))) },
  }
}

describe('seed vectors shared with Rust', () => {
  it('match what this implementation makes', () => {
    const made = current()
    if (process.env.KUTUP_WRITE_SEED_VECTORS === '1') writeFileSync(FILE, JSON.stringify(made, null, 2) + '\n')
    expect(JSON.parse(readFileSync(FILE, 'utf8'))).toEqual(made)
  })
})
