import { deterministicSeed } from '@kutup/collab/session'
import { fillDoc, parseListJson, uploadPlaceId, type Place } from '@kutup/map/list'

/** The repository root: the nearest folder up from here holding `crates/kutup-collab`. */
function repoRoot(): string {
  let dir = process.cwd()
  while (!existsSync(join(dir, 'crates', 'kutup-collab'))) {
    const up = dirname(dir)
    if (up === dir) throw new Error('crates/kutup-collab not found above the working directory')
    dir = up
  }
  return dir
}

const FILE = join(repoRoot(), 'crates', 'kutup-collab', 'tests', 'vectors', 'seeds.json')
const FILE_ID = '11111111-1111-4111-8111-111111111111'

const TEXTS: Record<string, string> = {
  empty: '',
  note: '# Plans\n\n- milk\n- bread\n',
  code: 'fn main() {\n    println!("hi");\n}\n',
  // Non-BMP (two UTF-16 units each) and Turkish letters.
  unicode: '😀 İstanbul ılık ŞĞÜÖÇ 🎉\n',
}

const PLACES: Place[] = [
  { id: 'p1', name: 'Galata Kulesi', note: 'sunset', lat: 41.0256, lon: 28.9741, addedBy: 'ali@kutup.dev', addedAt: '2026-01-02T10:00:00.000Z' },
  { id: 'p2', name: 'Kız Kulesi 🗼', note: '', lat: 41.021, lon: 29.0041, addedBy: 'ali@kutup.dev', addedAt: '2026-01-02T11:00:00.000Z' },
  { id: 'p3', name: 'Zero', note: 'integers', lat: 41, lon: 29, addedBy: 'ali@kutup.dev', addedAt: '2026-01-03T00:00:00.000Z' },
]

const hex = (bytes: Uint8Array) => Buffer.from(bytes).toString('hex')
const utf8 = (text: string) => new TextEncoder().encode(text)
const BOM = [0xef, 0xbb, 0xbf]

// Files as uploaded: what a note's or a list's first editor seeds from, read
// the way the editors read them (TextDecoder; parseListJson with the upload's
// place ids). Rust: seed_text_upload / seed_list_upload.
const TEXT_FILES: Record<string, Uint8Array> = {
  bom: new Uint8Array([...BOM, ...utf8('# Notlar\n')]),
  crlf: utf8('one\r\ntwo\r\n'),
  invalidUtf8: new Uint8Array([0x61, 0xff, 0x62, 0xc3, 0x28, 0x0a]),
}
const LIST_FILES: Record<string, Uint8Array> = {
  bomAndMissingIds: new Uint8Array([
    ...BOM,
    ...utf8(JSON.stringify({ format: 'kutupmap', version: 1, places: [
      { name: 'No id', lat: 41, lon: 29 },
      { id: 'bad id!', name: 'Bad id', lat: 41.5, lon: 29.5, addedAt: '2026-10-13T10:00:00Z' },
      { id: 'k', name: 'Kept', lat: 40, lon: 28, addedAt: '2026-02-29T10:00:00Z' },
    ] })),
  ]),
  oddFields: utf8(JSON.stringify({ format: 'kutupmap', version: 1.0, places: [
    { id: 'a', name: '\u00a0 Trimmed \u00a0', lat: 41, lon: 29, addedAt: '2026-10-13' },
    { id: 'b', name: 'String lat', lat: '41', lon: 29 },
    { id: 'c', name: 'Offset', lat: -12.5, lon: 180, addedAt: '2026-10-13T10:00:00.5+03:00', note: 'n' },
    { id: 'c', name: 'Duplicate id', lat: 1, lon: 1 },
  ] })),
  notAList: utf8('{"format":"other"}'),
}

async function current() {
  return {
    description:
      'Seeds a file’s first editor makes (deterministicSeed: the content inserted once, a Yjs V1 update, under the client id kutup_crypto::yjs_seed derives from the file id and that update made under client id 0). Generated by the web (Yjs, frontend/apps/maps/src/features/lists/seedVectors.test.ts); crates/kutup-collab (yrs) must produce the same bytes. A Yjs or yrs bump must keep both passing.',
    fileId: FILE_ID,
    texts: await Promise.all(
      Object.entries(TEXTS).map(async ([name, text]) => ({
        name,
        text,
        seed: hex(await deterministicSeed(FILE_ID, (doc) => doc.getText('content').insert(0, text))),
      })),
    ),
    list: { places: PLACES, seed: hex(await deterministicSeed(FILE_ID, (doc) => fillDoc(doc, PLACES))) },
    textUploads: await Promise.all(
      Object.entries(TEXT_FILES).map(async ([name, bytes]) => ({
        name,
        bytes: hex(bytes),
        seed: hex(await deterministicSeed(FILE_ID, (doc) => doc.getText('content').insert(0, new TextDecoder().decode(bytes)))),
      })),
    ),
    listUploads: await Promise.all(Object.entries(LIST_FILES).map(async ([name, bytes]) => {
      let places: Place[] = []
      try {
        places = parseListJson(bytes, (index) => uploadPlaceId(FILE_ID, index))
      } catch {
        // Not a list: it starts empty, as in the editor.
      }
      return { name, bytes: hex(bytes), seed: hex(await deterministicSeed(FILE_ID, (doc) => fillDoc(doc, places))) }
    })),
  }
}

describe('seed vectors shared with Rust', () => {
  it('match what this implementation makes', async () => {
    const made = await current()
    if (process.env.KUTUP_WRITE_SEED_VECTORS === '1') writeFileSync(FILE, JSON.stringify(made, null, 2) + '\n')
    expect(JSON.parse(readFileSync(FILE, 'utf8'))).toEqual(made)
  })
})
